#pragma once

#define PROXY_VERSION 2u
#define PROXY_CONTEXT_MAGIC 0x31504657u
#define PROXY_IPV4 1u
#define PROXY_IPV6 2u
#define PROXY_UDP 1u
#define PROXY_DNS 2u
#define PROXY_MAX_APP_ID 8192u
#define PROXY_ARM CTL_CODE(FILE_DEVICE_UNKNOWN, 0x800, METHOD_BUFFERED, FILE_WRITE_ACCESS)
#define PROXY_HEARTBEAT CTL_CODE(FILE_DEVICE_UNKNOWN, 0x801, METHOD_BUFFERED, FILE_WRITE_ACCESS)
#define PROXY_DISARM CTL_CODE(FILE_DEVICE_UNKNOWN, 0x802, METHOD_BUFFERED, FILE_WRITE_ACCESS)
#define PROXY_READ_UDP CTL_CODE(FILE_DEVICE_UNKNOWN, 0x803, METHOD_BUFFERED, FILE_WRITE_ACCESS)
#define PROXY_REPLY_UDP CTL_CODE(FILE_DEVICE_UNKNOWN, 0x804, METHOD_BUFFERED, FILE_WRITE_ACCESS)
#define PROXY_UDP_DROPS CTL_CODE(FILE_DEVICE_UNKNOWN, 0x805, METHOD_BUFFERED, FILE_WRITE_ACCESS)

typedef struct _PROXY_REGISTRATION {
    UINT32 Version;
    UINT32 Size;
    UINT32 ListenPort;
    UINT32 Families;
    UINT32 TargetPort;
    UINT32 AppIdLength;
    UCHAR Target4[4];
    UCHAR Target6[16];
    UINT32 Flags;
    /* AppIdLength bytes of the FwpmGetAppIdFromFileName0 blob follow. */
} PROXY_REGISTRATION;

typedef struct _PROXY_REDIRECT_CONTEXT {
    UINT32 Magic;
    UINT32 Size;
    UINT32 Family;
    UINT32 Port;
    UINT32 Scope;
    UCHAR Address[16];
} PROXY_REDIRECT_CONTEXT;

typedef struct _PROXY_UDP_HEADER {
    UINT64 Cookie;
    UINT32 Family;
    UINT32 Port;
    UCHAR Address[16];
} PROXY_UDP_HEADER;

C_ASSERT(sizeof(PROXY_REGISTRATION) == 48);
C_ASSERT(sizeof(PROXY_REDIRECT_CONTEXT) == 36);
C_ASSERT(PROXY_ARM == 0x22a000);
C_ASSERT(PROXY_HEARTBEAT == 0x22a004);
C_ASSERT(PROXY_DISARM == 0x22a008);
C_ASSERT(PROXY_READ_UDP == 0x22a00c);
C_ASSERT(PROXY_REPLY_UDP == 0x22a010);
C_ASSERT(PROXY_UDP_DROPS == 0x22a014);
C_ASSERT(sizeof(PROXY_UDP_HEADER) == 32);
